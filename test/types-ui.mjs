import { chromium } from 'playwright-core';
import path from 'node:path';
const ext = path.resolve('dist');
const ctx = await chromium.launchPersistentContext('', { executablePath: process.argv[2], headless: true, args: [`--disable-extensions-except=${ext}`, `--load-extension=${ext}`, '--headless=new'], viewport: { width: 1100, height: 900 } });
let [sw] = ctx.serviceWorkers(); if (!sw) sw = await ctx.waitForEvent('serviceworker');
const id = sw.url().split('/')[2];
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('pageerror', e.message));
await page.goto(`chrome-extension://${id}/options.html#data`); await page.waitForTimeout(800);
console.log('строк типов:', await page.locator('#types tr').count());
await page.fill('#typeTest', 'Device IMEI #1'); console.log(await page.textContent('#typeTestOut'));
await page.fill('#typeFilter', 'imei');
const row = page.locator('#types tr').first();
await row.locator('textarea').first().fill('imei|имей|serial');
await row.locator('textarea').nth(1).fill('/35[0-9]{13}/');
console.log('пример:', await row.locator('.preview').textContent());
await page.fill('#typeTest', 'serial'); console.log('serial →', await page.textContent('#typeTestOut'));
await page.waitForTimeout(700);
console.log(JSON.stringify(await sw.evaluate(async () => { const { settings } = await chrome.storage.local.get('settings'); return [settings.typePatterns, settings.typeValues, settings.refillFilled]; })));
await page.fill('#typeFilter', '');
await page.locator('#types').scrollIntoViewIfNeeded();
await page.screenshot({ path: 'test/types.png', clip: { x: 0, y: (await page.locator('#types').boundingBox()).y - 160, width: 1100, height: 700 } });
const pop = await ctx.newPage(); await pop.goto(`chrome-extension://${id}/popup.html`); await pop.waitForTimeout(400);
await pop.screenshot({ path: 'test/popup.png' });
await ctx.close();
