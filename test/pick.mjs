// Element pick mode: hover, click, inspect the panel, save the rule
import { chromium } from 'playwright-core';
import http from 'node:http';
import { readFileSync } from 'node:fs';
import path from 'node:path';
const site = path.resolve('test/site');
const server = http.createServer((req, res) => { try { res.end(readFileSync(path.join(site, req.url.split('?')[0]))); } catch { res.statusCode = 404; res.end(); } }).listen(8781);
const ext = path.resolve('dist');
const ctx = await chromium.launchPersistentContext('', { executablePath: process.argv[2], headless: true, args: [`--disable-extensions-except=${ext}`, `--load-extension=${ext}`, '--headless=new'], viewport: { width: 1280, height: 900 } });
let [sw] = ctx.serviceWorkers(); if (!sw) sw = await ctx.waitForEvent('serviceworker');
const lang = process.argv[4] || 'ru';
await sw.evaluate(async ([l, th]) => { const { settings = {} } = await chrome.storage.local.get('settings'); await chrome.storage.local.set({ settings: { ...settings, uiLang: l, theme: th } }); }, [lang, process.argv[5] || 'light']);
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('pageerror', e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text()); });
await page.goto('http://localhost:8781/' + (process.argv[3] || 'mifos-client.html')); await page.waitForTimeout(600);
const sel = process.argv[6] || 'input[name="mobileNo"], #mobileNo, input[ng-model*="mobile" i]';
await sw.evaluate(async () => { const [t] = await chrome.tabs.query({ url: 'http://localhost:8781/*' }); return self.__ffp.broadcast(t.id, { action: 'pick' }); });
await page.waitForTimeout(400);
const box = await page.locator(sel).first().boundingBox();
await page.mouse.move(box.x + 10, box.y + box.height / 2); await page.waitForTimeout(200);
await page.screenshot({ path: 'test/pick-hover.png' });
await page.mouse.click(box.x + 10, box.y + box.height / 2); await page.waitForTimeout(500);
await page.screenshot({ path: 'test/pick-panel.png' });
// save: the buttons live inside a closed shadow root, so clicking by coordinates or finding them via elementFromPoint won't work; use Tab+Enter
const host = page.locator('formigo-picker');
console.log('панель есть:', await host.count());
const sh = (js) => page.evaluate(js);
await sh(() => { const r = document.querySelector('formigo-picker').shadowRoot; [...r.querySelectorAll('.chip')].find((b) => /цифр|digit/i.test(b.textContent))?.click(); });
await page.waitForTimeout(200);
await sh(() => [...document.querySelector('formigo-picker').shadowRoot.querySelectorAll('.btn')].pop().click());
await page.waitForTimeout(900);
console.log('правило:', JSON.stringify(await sw.evaluate(async () => (await chrome.storage.local.get('settings')).settings.rules[0])));
console.log('значение поля:', await page.inputValue(sel));
console.log('слоёв на странице:', await host.count());
await page.screenshot({ path: 'test/pick-saved.png' });
await sw.evaluate(async () => { const [t] = await chrome.tabs.query({ url: 'http://localhost:8781/*' }); return self.__ffp.broadcast(t.id, { action: 'pick' }); });
await page.waitForTimeout(300);
console.log('до Esc:', await host.count()); await page.keyboard.press('Escape'); await page.waitForTimeout(2500);
console.log('после Esc:', await host.count());
await page.close();
await ctx.close(); server.close();
